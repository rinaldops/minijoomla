// Minimal DOM for the markup generated by renderMenuTree (no void elements, quoted attributes).
class Node {
  constructor(tag, attributes = {}, parent = null) {
    Object.assign(this, { tag, attributes, parent, children: [], listeners: new Map(), focused: 0, ownerDocument: null });
    const node = this;
    this.classList = {
      toggle(name, force) { const set = new Set((node.attributes.class ?? '').split(/\s+/).filter(Boolean)); if (force ?? !set.has(name)) set.add(name); else set.delete(name); node.attributes.class = [...set].join(' '); },
      contains(name) { return (node.attributes.class ?? '').split(/\s+/).includes(name); }
    };
  }
  getAttribute(name) { return name in this.attributes ? this.attributes[name] : null; }
  setAttribute(name, value) { this.attributes[name] = String(value); }
  removeAttribute(name) { delete this.attributes[name]; }
  hasAttribute(name) { return name in this.attributes; }
  focus() { this.focused += 1; }
  addEventListener(type, listener) { if (!this.listeners.has(type)) this.listeners.set(type, new Set()); this.listeners.get(type).add(listener); }
  removeEventListener(type, listener) { this.listeners.get(type)?.delete(listener); }
  listenerCount() { return [...this.listeners.values()].reduce((total, set) => total + set.size, 0); }
  contains(node) { for (let current = node; current; current = current.parent) if (current === this) return true; return false; }
  matches(selector) {
    const match = /^([a-z0-9]*)((?:\[[^\]]+\])*)$/.exec(selector.trim());
    if (!match) throw new Error(`unsupported selector ${selector}`);
    if (match[1] && match[1] !== this.tag) return false;
    return [...match[2].matchAll(/\[([\w-]+)(?:="([^"]*)")?\]/g)].every(([, name, value]) => this.hasAttribute(name) && (value === undefined || this.attributes[name] === value));
  }
  closest(selector) { for (let current = this; current && current.tag !== '#document'; current = current.parent) if (current.matches(selector)) return current; return null; }
  querySelectorAll(selector) { const found = []; const walk = (node) => node.children.forEach((child) => { if (child.matches(selector)) found.push(child); walk(child); }); walk(this); return found; }
  querySelector(selector) { return this.querySelectorAll(selector)[0] ?? null; }
}

function parse(html) {
  const documentNode = new Node('#document');
  documentNode.ownerDocument = null;
  let current = documentNode;
  for (const [, closing, tag, rest] of html.matchAll(/<(\/?)([a-z0-9]+)([^>]*)>/g)) {
    if (closing) { assert.equal(current.tag, tag, 'balanced markup'); current = current.parent; continue; }
    const attributes = Object.fromEntries([...rest.matchAll(/([\w-]+)(?:="([^"]*)")?/g)].map(([, name, value]) => [name, value ?? '']));
    const node = new Node(tag, attributes, current);
    node.ownerDocument = documentNode;
    current.children.push(node);
    current = node;
  }
  assert.equal(current, documentNode, 'all elements closed');
  return documentNode;
}

function dispatch(node, type, init = {}) {
  const event = { type, target: node, defaultPrevented: false, propagationStopped: false, preventDefault() { this.defaultPrevented = true; }, stopPropagation() { this.propagationStopped = true; }, ...init };
  for (let current = node; current && !event.propagationStopped; current = current.parent) for (const listener of [...(current.listeners.get(type) ?? [])]) listener(event);
  return event;
}

const tree = [
  { id: 1, title: 'Início', path: '/', ordering: 1 },
  { id: 2, title: 'Serviços', path: '/servicos', ordering: 2 },
  { id: 3, title: 'Zeta', path: '/servicos/zeta', parentId: 2, ordering: 2 },
  { id: 4, title: 'Alfa', path: '/servicos/alfa', parentId: 2, ordering: 1 },
  { id: 5, title: 'Detalhe', path: '/servicos/alfa/detalhe', parentId: 4 },
  { id: 6, title: 'Rascunho', path: '/rascunho', published: false, ordering: 0 },
  { id: 7, title: 'Filho oculto', path: '/rascunho/filho', parentId: 6 },
  { id: 8, title: 'Neto oculto', path: '/rascunho/filho/neto', parentId: 7 },
  { id: 9, title: 'Contato', path: '/contato', ordering: 3, parentId: 999 }
];

export async function runMenuTreeTests() {
  // Flat menus keep the historical markup.
  const flat = menuModule.render({ menus: [{ title: 'B', path: '/b' }, { title: 'A', path: '/a', ordering: 2 }, { title: 'X', path: '/x', published: 0 }], activePath: '/b' });
  assert.equal(flat, '<nav aria-label="Menu principal"><ul><li><a href="#/a">A</a></li><li><a href="#/b" aria-current="page">B</a></li></ul></nav>');
  assert.equal(menuModule.render({ menus: 'invalid' }), '<nav aria-label="Menu principal"><ul></ul></nav>');
  assert.ok(compareMenuItems({ ordering: '1' }, { ordering: 2 }) < 0);
  assert.ok(compareMenuItems({ title: 'b' }, { ordering: 9 }) > 0);

  // Tree building: ordering, published only, hidden descendants, missing parents.
  const forest = buildMenuTree(tree);
  const shape = (nodes) => nodes.map((node) => node.children.length ? [node.item.title, shape(node.children)] : node.item.title);
  assert.deepEqual(shape(forest), ['Início', ['Serviços', [['Alfa', ['Detalhe']], 'Zeta']], 'Contato']);
  assert.equal(forest[1].children[0].children[0].depth, 3);

  // Cycles and self references terminate and keep every published item exactly once.
  const cyclic = [
    { id: 'a', title: 'A', path: '/a', parentId: 'b' }, { id: 'b', title: 'B', path: '/b', parentId: 'c' },
    { id: 'c', title: 'C', path: '/c', parentId: 'a' }, { id: 'd', title: 'D', path: '/d', parentId: 'd' },
    { id: 'e', title: 'E', path: '/e', parentId: 'a' }, null, 'junk', { id: { nested: true }, title: 'Obj' }
  ];
  const cyclicForest = buildMenuTree(cyclic);
  const titles = [];
  const collect = (nodes) => nodes.forEach((node) => { titles.push(node.item.title); collect(node.children); });
  collect(cyclicForest);
  assert.deepEqual([...titles].sort(), ['A', 'B', 'C', 'D', 'E', 'Obj']);
  assert.deepEqual(shape(cyclicForest), [['A', [['C', ['B']], 'E']], 'D', 'Obj']);
  const large = Array.from({ length: 2000 }, (_, index) => ({ id: index + 1, title: `I${index}`, path: `/${index}`, parentId: ((index + 1) % 2000) + 1 }));
  assert.equal(buildMenuTree(large).length, 1);

  // Tree markup: classes, toggles, active trail, escaping.
  const html = renderMenuTree({ menus: [...tree, { id: 10, title: '<b>"x"</b>', path: '/servicos/"x"', parentId: 2, ordering: 3 }], activePath: '/servicos/alfa/detalhe' });
  assert.match(html, /^<nav aria-label="Menu principal" class="mod-menu-tree" data-menu-tree><ul class="mod-menu mod-menu_dropdown-metismenu metismenu level-1">/);
  assert.doesNotMatch(html, /Rascunho|oculto|<b>|onclick|<script/);
  assert.match(html, /&lt;b&gt;&quot;x&quot;&lt;\/b&gt;/);
  assert.match(html, /<li class="metismenu-item item-2 level-1 deeper parent active"><a href="#\/servicos">Serviços<\/a><button type="button" class="mm-toggler mm-toggler-link" aria-expanded="false" aria-controls="(mj-menu-\d+-sub-1)" aria-label="Submenu de Serviços" data-menu-tree-toggle hidden>/);
  assert.match(html, /<li class="metismenu-item item-5 level-3 active current"><a href="#\/servicos\/alfa\/detalhe" aria-current="page">Detalhe<\/a><\/li>/);
  assert.match(html, /<li class="metismenu-item item-1 level-1"><a href="#\/">Início<\/a><\/li>/);
  assert.equal((html.match(/aria-current="page"/g) ?? []).length, 1);
  assert.equal((html.match(/<nav /g) ?? []).length, 1);
  assert.doesNotMatch(html, /class="mm-collapse[^"]*mm-show/, 'links stay visible without JavaScript');
  const ids = (markup) => [...markup.matchAll(/ id="([^"]+)"/g)].map(([, id]) => id);
  const second = menuModule.render({ menus: tree, activePath: '/' });
  const allIds = [...ids(html), ...ids(second)];
  assert.equal(new Set(allIds).size, allIds.length, 'no duplicate ids across instances');
  for (const id of ids(html)) assert.ok(html.includes(`aria-controls="${id}"`));
  assert.match(renderMenuTree({ menus: [{ id: 'x y"', title: 'P' }, { id: 2, title: 'C', parentId: 'x y"' }], idPrefix: '"bad prefix' }), /class="metismenu-item item-xy level-1 deeper parent".*aria-controls="badprefix-\d+-sub-1"/);

  // Binding: toggles become visible, aria-expanded/aria-controls, Escape, outside click, cleanup.
  const doc = parse(`<div id="host">${html}<a href="#other">fora</a></div><div>${second}</div>`);
  const navs = doc.querySelectorAll('[data-menu-tree]');
  assert.equal(navs.length, 2);
  const release = bindMenuTree(doc);
  assert.equal(bindMenuTree(doc).call(null), undefined, 'already bound trees are not bound twice');
  const [nav] = navs;
  assert.ok(nav.hasAttribute('data-menu-tree-js'));
  const toggles = nav.querySelectorAll('[data-menu-tree-toggle]');
  assert.equal(toggles.length, 2);
  assert.ok(toggles.every((toggle) => !toggle.hasAttribute('hidden')));
  const [servicesToggle, alfaToggle] = toggles;
  const servicesSub = nav.querySelector(`[id="${servicesToggle.getAttribute('aria-controls')}"]`);
  const alfaSub = nav.querySelector(`[id="${alfaToggle.getAttribute('aria-controls')}"]`);
  assert.equal(dispatch(servicesToggle, 'click').defaultPrevented, true);
  assert.equal(servicesToggle.getAttribute('aria-expanded'), 'true');
  assert.ok(servicesSub.classList.contains('mm-show'));
  dispatch(alfaToggle, 'click');
  assert.ok(alfaSub.classList.contains('mm-show'));
  const deepLink = alfaSub.querySelector('a');
  const shellListener = { calls: 0 };
  doc.addEventListener('keydown', () => { shellListener.calls += 1; });
  const escape = dispatch(deepLink, 'keydown', { key: 'Escape' });
  assert.equal(escape.defaultPrevented, true);
  assert.equal(shellListener.calls, 0, 'handled Escape does not close the shell mobile menu');
  assert.equal(alfaToggle.getAttribute('aria-expanded'), 'false');
  assert.equal(alfaToggle.focused, 1);
  assert.ok(servicesSub.classList.contains('mm-show'), 'only the innermost submenu closes');
  dispatch(alfaToggle, 'keydown', { key: 'Escape' });
  assert.equal(servicesToggle.getAttribute('aria-expanded'), 'false');
  assert.equal(servicesToggle.focused, 1);
  dispatch(servicesToggle, 'keydown', { key: 'Escape' });
  assert.equal(shellListener.calls, 1, 'unhandled Escape bubbles to the shell');
  dispatch(nav.querySelector('a'), 'keydown', { key: 'Enter' });
  dispatch(servicesToggle, 'click');
  dispatch(alfaToggle, 'click');
  dispatch(servicesToggle, 'click');
  assert.equal(alfaToggle.getAttribute('aria-expanded'), 'false', 'closing a parent closes nested submenus');
  dispatch(servicesToggle, 'click');
  dispatch(doc.querySelector('[href="#other"]'), 'click');
  assert.equal(servicesToggle.getAttribute('aria-expanded'), 'false', 'outside click closes');
  dispatch(servicesToggle, 'click');
  dispatch(nav.querySelector('a'), 'click');
  assert.equal(servicesToggle.getAttribute('aria-expanded'), 'true', 'click inside keeps state');

  const otherToggle = navs[1].querySelector('[data-menu-tree-toggle]');
  dispatch(otherToggle, 'click');
  assert.equal(otherToggle.getAttribute('aria-expanded'), 'true');
  assert.equal(servicesToggle.getAttribute('aria-expanded'), 'false', 'interacting with another instance counts as outside click');
  assert.equal(navs[1].querySelector(`[id="${otherToggle.getAttribute('aria-controls')}"]`).classList.contains('mm-show'), true, 'each instance controls its own submenu');

  release();
  release();
  assert.equal(doc.listeners.get('click')?.size ?? 0, 0);
  for (const element of navs) {
    assert.equal(element.listenerCount(), 0);
    assert.equal(element.hasAttribute('data-menu-tree-js'), false);
    assert.ok(element.querySelectorAll('[data-menu-tree-toggle]').every((toggle) => toggle.hasAttribute('hidden') && toggle.getAttribute('aria-expanded') === 'false'));
    assert.ok(element.querySelectorAll('[data-menu-tree-submenu]').every((submenu) => !submenu.classList.contains('mm-show')));
  }
  const releaseNav = bindMenuTree(nav);
  assert.ok(nav.hasAttribute('data-menu-tree-js'), 'the nav itself can be the root');
  releaseNav();
  assert.equal(typeof bindMenuTree(null), 'function');
  assert.doesNotThrow(() => bindMenuTree({})());

  console.log('menu tree: ordering, publication, orphans, cycles, active trail, escaping, toggles, Escape and cleanup approved');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  runMenuTreeTests().catch((error) => { console.error(error); process.exitCode = 1; });
}
