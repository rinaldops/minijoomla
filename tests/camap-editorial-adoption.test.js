function documentDouble(packages) {
  const links = [];
  const cssReads = [];
  const removed = [];
  return { links, cssReads, removed, baseURI: 'https://editorial.invalid/local.html',
    head: { appendChild(link) {
      links.push(link);
      assert.equal(link.rel, 'stylesheet');
      assert.equal(link['data-mj-module-style'], '');
      const pack = packages.find((item) => `https://editorial.invalid${item.cssUrl}` === link.href);
      assert.ok(pack, 'CSS must use the selected verified revision');
      cssReads.push(pack.root.files.downloadFile({ folderPath: `media/${ELEMENT}/css`, fileName: 'db.css' }).then((data) => {
        assert.equal(digest(data), HASHES[CSS]);
        return { version: pack.version, bytes: data.length, href: link.href };
      }));
    } },
    createElement(tag) {
      assert.equal(tag, 'link');
      return { setAttribute(name, value) { this[name] = value; }, remove() {
        removed.push(this); const index = links.indexOf(this); if (index >= 0) links.splice(index, 1);
      } };
    }
  };
}

