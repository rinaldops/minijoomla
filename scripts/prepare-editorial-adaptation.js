async function writeNewFiles(root, files) {
  for (const [name, bytes] of files) {
    packagePath(name);
    const path = join(root, ...name.split('/'));
    await assertAdoptionNoLinks(path, { allowMissing: true });
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, bytes, { flag: 'wx' });
  }
}

async function diskFiles(root, prefix = '', budget = { count: 0, bytes: 0 }) {
  await assertAdoptionNoLinks(join(root, prefix));
  const entries = await readdir(join(root, prefix), { withFileTypes: true });
  const files = new Map();
  for (const entry of entries) {
    const name = prefix ? `${prefix}/${entry.name}` : entry.name;
    packagePath(name);
    if (++budget.count > MAX_FILES || entry.isSymbolicLink()) throw new Error('Package paths/count contract exceeded.');
    if (entry.isDirectory()) for (const [path, bytes] of await diskFiles(root, name, budget)) files.set(path, bytes);
    else {
      const path = join(root, ...name.split('/'));
      await assertAdoptionNoLinks(path);
      const stat = await lstat(path);
      if (!stat.isFile() || stat.size > MAX_BYTES || (budget.bytes += stat.size) > MAX_BYTES) throw new Error('Package bytes/type contract exceeded.');
      const bytes = await readFile(path);
      if (stat.size !== bytes.length) throw new Error('Package changed while reading.');
      files.set(name, bytes);
    }
  }
  return files;
}

/** Final inventory is formed in memory; staging outputs are never overwritten. */
export function finalizeEditorialPackage(stagedFiles, provenance) {
  const files = new Map(stagedFiles);
  if (!Array.isArray(provenance.licenses) || new Set(provenance.licenses).size !== provenance.licenses.length || provenance.licenses.some(name => !LICENSE_NAMES.includes(name))) throw new Error('Unapproved original license paths.');
  const controls = new Set(['MANIFEST-SHA256.json', 'host-config.json', 'adoption-plan.json', 'docs/ADOPTION-NOTICE.md', ...provenance.licenses]);
  const runtimePath = name => name === `libraries/camap/${SHARED_SOURCE_PATH}` || [`modules/${MODULE}/`, `media/${MODULE}/`, `libraries/camap/extensions/camap/${MODULE}/`].some(prefix => name.startsWith(prefix));
  const mandatory = [`modules/${MODULE}/${MODULE}.js`, `modules/${MODULE}/${MODULE}.xml`, `media/${MODULE}/css/db.css`, `libraries/camap/${EDITORIAL_SOURCE_PATH}`, `libraries/camap/${SHARED_SOURCE_PATH}`];
  for (const name of files.keys()) {
    packagePath(name);
    if (!controls.has(name) && !runtimePath(name)) throw new Error(`Staged path outside editorial allowlist: ${name}`);
  }
  if (mandatory.some(name => !files.has(name))) throw new Error('Missing mandatory editorial runtime payload.');
  const wrapper = Buffer.from(`export { default } from '../../libraries/camap/${EDITORIAL_SOURCE_PATH}';\nexport * from '../../libraries/camap/${EDITORIAL_SOURCE_PATH}';\n`);
  if (!Buffer.isBuffer(files.get(mandatory[0])) || !files.get(mandatory[0]).equals(wrapper)) throw new Error('Editorial wrapper differs from original generator.');
  const inventoryBytes = files.get('MANIFEST-SHA256.json');
  if (!inventoryBytes || inventoryBytes.length > 64 * 1024) throw new Error('Missing/oversized staged inventory.');
  const inventory = JSON.parse(inventoryBytes);
  const hostConfig = JSON.parse(files.get('host-config.json'));
  if (inventory.format !== 'minijoomla-joomla-package-v1' || !Array.isArray(inventory.files) || inventory.files.length > MAX_FILES) throw new Error('Unexpected staged inventory.');
  const expected = new Set(['MANIFEST-SHA256.json', 'host-config.json']);
  for (const entry of inventory.files) {
    packagePath(entry.path);
    const bytes = files.get(entry.path);
    if (expected.has(entry.path) || !bytes || entry.bytes !== bytes.length || entry.sha256 !== sha256(bytes)) throw new Error('Staged inventory integrity failure.');
    expected.add(entry.path);
  }
  if (expected.size !== files.size || [...files.keys()].some(name => !expected.has(name))) throw new Error('Uninventoried staged file.');
  if (hostConfig.joomlaDiscoveryRoots?.length !== 1 || hostConfig.joomlaDiscoveryRoots[0].inventoryHash !== sha256(inventoryBytes)) throw new Error('Staged control hash differs.');
  const adoptionPlan = JSON.parse(files.get('adoption-plan.json'));
  if (adoptionPlan.module !== MODULE || adoptionPlan.version !== inventory.version || adoptionPlan.base !== hostConfig.joomlaDiscoveryRoots[0].baseUrl) throw new Error('Staged identity differs.');
  if (files.has('ADAPTATION.json') || files.has('docs/ADAPTATION-NOTICE.md')) throw new Error('Already adapted package refused.');
  const licenses = LICENSE_NAMES.filter(name => files.has(name)).sort();
  if (JSON.stringify(licenses) !== JSON.stringify([...provenance.licenses].sort())) throw new Error('Original license inventory differs.');
  if (provenance.changes?.length !== 2 || new Set(provenance.changes.map(change => change.path)).size !== 2 || provenance.changes.some(change => !EDITORIAL_ANCHORS[change.path]?.includes(change.originalSha256))) throw new Error('Unapproved adaptation provenance.');
  if (!GENERATOR_HASHES.includes(provenance.generatorSha256)) throw new Error('Unapproved original generator provenance.');
  for (const change of provenance.changes) {
    const bytes = files.get(`libraries/camap/${change.path}`);
    if (!bytes || sha256(bytes) !== change.generatedSha256) throw new Error('Packaged overlay differs from approved patch.');
  }
  const changesLicense = provenance.changesLicenseSource;
  const gpl = provenance.changesLicenseBytes;
  if (!changesLicense || !Buffer.isBuffer(gpl) || sha256(gpl) !== CHANGES_LICENSE_SHA256 || changesLicense.sha256 !== CHANGES_LICENSE_SHA256 || changesLicense.path !== CHANGES_LICENSE_PATH || changesLicense.license !== 'GPL-2.0-or-later' || changesLicense.scope !== 'authored adaptation changes only') throw new Error('Missing/invalid authored changes GPL license evidence.');
  const inherited = provenance.inheritedLicense;
  const notice = provenance.inheritedLicenseBytes;
  if (!inherited || !Buffer.isBuffer(notice) || !MIT_HASHES.includes(sha256(notice)) || inherited.sha256 !== sha256(notice) || inherited.originCommit !== ORIGIN_COMMIT || inherited.packagePath !== INHERITED_LICENSE_PATH || JSON.stringify(inherited.scope) !== JSON.stringify([EDITORIAL_SOURCE_PATH, SHARED_SOURCE_PATH, CSS_SOURCE_PATH])) throw new Error('Missing/invalid scoped inherited MIT evidence.');
  if (sha256(files.get(`media/${MODULE}/css/db.css`)) !== CSS_LF_HASH) throw new Error('Packaged CSS differs from historical MIT scope.');
  files.set(INHERITED_LICENSE_PATH, notice); // exact source bytes, no reconstruction
  files.set(CHANGES_LICENSE_PATH, gpl); // exact full text for authored changes only
  for (const flag of ['publicationApproved', 'rightsApproved', 'migrated', 'tenantModified', 'hostConfigured', 'currentRecordsModified']) adoptionPlan[flag] = false;
  adoptionPlan.licenses = [...licenses, INHERITED_LICENSE_PATH];
  adoptionPlan.sourceRootLicensePresent = licenses.length > 0;
  adoptionPlan.sourceLicensePresent = true;
  adoptionPlan.inheritedLicenseSource = inherited;
  adoptionPlan.changesLicenseSource = changesLicense;
  adoptionPlan.adaptation = { format: 'minijoomla-editorial-adaptation-v1', revision: 1, provenance: 'ADAPTATION.json', changesLicense: 'GPL-2.0-or-later', vendorRightsCleared: false };
  adoptionPlan.nextGate = 'Independent rights review and coordinator lifecycle verification; no installation or publication approval.';
  const adaptation = { format: 'minijoomla-editorial-adaptation-v1', revision: 1, module: MODULE, version: inventory.version,
    originalSource: 'local CAMAP2 read-only bounded snapshot', changes: provenance.changes,
    generator: { path: 'tools/prepare-joomla-modules.js', sha256: provenance.generatorSha256, algorithmModified: false },
    adoptionApi: { path: 'scripts/prepare-module-adoption.js', sha256: provenance.adoptionApiSha256, byteIdenticalRelocation: true },
    snapshot: provenance.snapshot, originalLicenses: licenses, inheritedLicenseSource: inherited, changesLicense: 'GPL-2.0-or-later', changesLicenseSource: changesLicense,
    vendorLicenseAssigned: false, rightsApproved: false, publicationApproved: false, currentRecordsModified: false,
    schemaModified: false, otherPackagesModified: false,
    policy: 'Fragments, non-protocol-relative server paths and credential-free HTTPS only; unsafe links become # and unsafe CTA is omitted; inert valid rows filtered only at render time.' };
  files.delete('MANIFEST-SHA256.json');
  files.delete('host-config.json');
  files.set('adoption-plan.json', json(adoptionPlan));
  files.set('ADAPTATION.json', json(adaptation));
  files.set('docs/ADAPTATION-NOTICE.md', Buffer.from('Local editorial adaptation, revision 1. Only the two sources named in ADAPTATION.json are patched in a private snapshot. XML fields/defaults, CSS, escapeHtml and stateMessage are unchanged. Invalid rows are filtered at render time only; stored settings are not rewritten. The shared helper affects this new package, not the pilot or other previously generated packages. GPL-2.0-or-later covers only authored changes and does not relicense CAMAP as a whole; the complete license is retained verbatim in docs/licenses/GPL-2.0.txt with its source hash and limited scope in ADAPTATION.json. The original aggregator MIT notice is retained verbatim in docs/licenses/CAMAP-ROOT-MIT.txt, scoped to the editorial/helper/CSS hashes and introduction commit recorded in ADAPTATION.json. Missing CAMAP-root notices alone are not a rights blocker; independent coordinator review of the selected package and any additional material remains required. No browser, tenant, installation, publication or global rights clearance is implied.\n'));
  let total = 0;
  const seen = new Set();
  for (const [name, bytes] of files) {
    packagePath(name);
    if (!controls.has(name) && !runtimePath(name) && !['ADAPTATION.json', 'docs/ADAPTATION-NOTICE.md', INHERITED_LICENSE_PATH, CHANGES_LICENSE_PATH].includes(name)) throw new Error('Final path outside editorial allowlist.');
    if (!Buffer.isBuffer(bytes) || seen.has(name.toLowerCase()) || (total += bytes.length) > MAX_BYTES) throw new Error('Final file contract exceeded.');
    seen.add(name.toLowerCase());
  }
  if (files.size + 2 > MAX_FILES) throw new Error('Final file count exceeded.');
  inventory.files = [...files].sort(([a], [b]) => a.localeCompare(b, 'en')).map(([path, bytes]) => ({ path, bytes: bytes.length, sha256: sha256(bytes) }));
  const finalInventoryBytes = json(inventory);
  if (finalInventoryBytes.length > 64 * 1024) throw new Error('Final inventory exceeds 64 KiB.');
  hostConfig.joomlaDiscoveryRoots[0].inventoryHash = sha256(finalInventoryBytes);
  files.set('MANIFEST-SHA256.json', finalInventoryBytes);
  files.set('host-config.json', json(hostConfig));
  return { files, inventory, hostConfig, adaptation, adoptionPlan };
}

export async function prepareEditorialAdaptation(input = {}) {
  const plan = planOptions(input);
  await mustBeNew(plan.destination);
  await assertAdoptionNoLinks(plan.source);
  await assertAdoptionNoLinks(plan.dependencies);
  const [sources, dependencies, inherited, api] = await Promise.all([collectSources(plan.source), collectDependencies(plan.dependencies), collectInheritedLicense(plan.inheritedLicense), (async () => {
    const collected = collector();
    for (const name of API_FILES) await collected.add(PROJECT, name);
    const gpl = await collected.add(PROJECT, CHANGES_LICENSE_PATH);
    if (sha256(gpl) !== CHANGES_LICENSE_SHA256) throw new Error('Authored changes GPL text differs from approved source hash.');
    return collected;
  })()]);
  await Promise.all([sources.collected.check(), dependencies.check(), inherited.collected.check(), api.check()]);
  await assertAdoptionNoLinks(TMP, { allowMissing: true });
  await mkdir(TMP, { recursive: true });
  const stage = await mkdtemp(join(TMP, 'editorial-adapt-stage-'));
  // Relocating byte-identical API + explicit static imports confines its private
  // TMP and snapshot paths too. No existing script, generator or import lexer is
  // patched; its supported isolated-dependencies routing is used as-is.
  await writeNewFiles(stage, new Map([...api.files.values()].map(({ name, bytes }) => [name, bytes])));
  await writeNewFiles(stage, new Map([['package.json', json({ private: true, type: 'module' })]]));
  const snapshot = join(stage, 'tmp', 'source');
  await writeNewFiles(snapshot, new Map([...sources.collected.files.values()].map(({ name, bytes }) => [name, sources.overlay.files.get(name) ?? bytes])));
  const deps = join(stage, 'tmp', 'dependencies');
  await writeNewFiles(deps, new Map([...dependencies.files.values()].map(({ name, bytes }) => [name, bytes])));
  await writeNewFiles(deps, new Map([['package.json', json({ private: true, type: 'module' })]]));
  const adoption = await import(pathToFileURL(join(stage, 'scripts', 'prepare-module-adoption.js')).href);
  const prepared = await adoption.prepareModuleAdoption({ module: MODULE, version: plan.args.version, base: plan.args.base, sourceRoot: snapshot, dependenciesRoot: deps, output: 'tmp/prepared' });
  const stagedFiles = await diskFiles(prepared.output);
  const provenance = { changes: sources.overlay.changes, licenses: sources.licenses,
    inheritedLicense: inherited.metadata, inheritedLicenseBytes: inherited.bytes,
    changesLicenseBytes: api.files.get(CHANGES_LICENSE_PATH.toLowerCase()).bytes,
    changesLicenseSource: { path: CHANGES_LICENSE_PATH, sha256: CHANGES_LICENSE_SHA256, license: 'GPL-2.0-or-later', scope: 'authored adaptation changes only' },
    generatorSha256: sha256(sources.collected.files.get('tools/prepare-joomla-modules.js').bytes),
    adoptionApiSha256: sha256(api.files.get('scripts/prepare-module-adoption.js').bytes),
    snapshot: [...sources.collected.files.values()].sort((a, b) => a.name.localeCompare(b.name, 'en')).map(({ name, bytes }) => ({ path: name, originalSha256: sha256(bytes), snapshotSha256: sha256(sources.overlay.files.get(name) ?? bytes), bytes: bytes.length })) };
  const finalized = finalizeEditorialPackage(stagedFiles, provenance);
  await Promise.all([sources.collected.check(), dependencies.check(), inherited.collected.check(), api.check()]);
  await mkdir(dirname(plan.destination), { recursive: true });
  await mustBeNew(plan.destination);
  await mkdir(plan.destination); // exclusive final reservation, no overwrites
  await writeNewFiles(plan.destination, finalized.files);
  return { ...finalized, output: plan.destination, stage, snapshot, originalSourceFiles: sources.collected.files.size, dependencyFiles: dependencies.files.size };
}

export function parseEditorialAdaptationArgs(argv = process.argv.slice(2)) {
  if (argv.length === 1 && ['--help', '-h'].includes(argv[0])) return { help: true };
  const args = {};
  for (let i = 0; i < argv.length; i += 2) {
    const key = argv[i];
    const name = { '--source': 'sourceRoot', '--dependencies-root': 'dependenciesRoot', '--inherited-license': 'inheritedLicense' }[key] ?? key.slice(2);
    if (!['--module', '--version', '--base', '--output', '--source', '--dependencies-root', '--inherited-license'].includes(key) || !argv[i + 1] || argv[i + 1].startsWith('--') || Object.hasOwn(args, name)) throw new Error('Invalid, duplicate or missing CLI argument.');
    args[name] = argv[i + 1];
  }
  return planOptions(args).args;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = parseEditorialAdaptationArgs();
    if (args.help) console.log('Usage: node scripts/prepare-editorial-adaptation.js --base /offline/editorial/0.3.0 --output tmp/editorial-adapt-new [--version 0.3.0] [--module mod_camap_editorial] [--source tmp/approved-source] [--dependencies-root tmp/step2/camap-source] [--inherited-license tmp/approved-MIT.txt]. Default inherited notice is approved ../LICENSE. Base must be explicitly supplied. Offline preparation only.');
    else {
      const result = await prepareEditorialAdaptation(args);
      console.log(`Prepared editorial ${result.inventory.version}: ${result.inventory.files.length} inventoried payloads, ${result.files.size} total files, ${result.originalSourceFiles} source and ${result.dependencyFiles} dependency snapshot files. Two patches only; rights/publication blocked. Output: ${result.output}`);
    }
  } catch (error) { console.error(`prepare-editorial-adaptation: ${error.message}`); process.exitCode = 1; }
}
